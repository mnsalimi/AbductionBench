"""Generate ``docs/datasets.md`` from the adapters' own documentation.

Every fact in the catalogue -- split used, abductive subset, sampling
procedure, metrics, decisions, caveats, item counts -- is read from each
adapter's ``documentation()`` and from a real ``prepare()`` + sampling pass, so
the document cannot drift from the code.

    python tools/dataset_catalogue.py configs/runs/pilot.yaml [output.md]
"""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from abductionbench.core.config import load_run_config  # noqa: E402
from abductionbench.core.engine import EvaluationEngine  # noqa: E402
from abductionbench.core.telemetry import setup_logging  # noqa: E402


def main() -> int:
    config_path = sys.argv[1] if len(sys.argv) > 1 else "configs/runs/pilot.yaml"
    out_path = Path(sys.argv[2] if len(sys.argv) > 2 else "docs/datasets.md")

    setup_logging(level="WARNING")
    config = load_run_config(config_path)
    engine = EvaluationEngine(config, dry_run=True)
    bundles = engine._build_bundles()  # noqa: SLF001 - stage A reuse is intentional

    # One dataset can produce several bundles -- a benchmark that poses
    # generation and selection as separate tasks is prepared once per task -- so
    # the catalogue is keyed by dataset and counts datasets, not bundles.
    evaluated: list = []
    skipped: list = []
    seen: set[str] = set()
    for bundle in bundles:
        if bundle.config.id in seen:
            continue
        seen.add(bundle.config.id)
        (skipped if bundle.skipped else evaluated).append(bundle)

    lines: list[str] = []
    lines.append("# Dataset catalogue")
    lines.append("")
    lines.append(
        "Generated by `python tools/dataset_catalogue.py` from each adapter's own "
        "`documentation()` plus a real preparation pass -- so every number and every "
        "stated decision below is what the code actually does."
    )
    lines.append("")
    lines.append(
        f"**{len(evaluated) + len(skipped)} datasets configured**: {len(evaluated)} "
        f"evaluable, {len(skipped)} reported as skipped. A dataset that poses generation and "
        f"selection as separate tasks is run as two, so a run plans more tasks than there are "
        f"datasets here."
    )
    lines.append("")

    # ---------------- summary table ---------------- #
    lines.append("## Summary")
    lines.append("")
    lines.append(
        "| dataset | domain | mode | items | split used | primary metric |"
    )
    lines.append("|---|---|---|---|---|---|")
    for bundle in sorted(evaluated, key=lambda b: b.config.id):
        doc = bundle.documentation
        lines.append(
            f"| `{bundle.config.id}` | {doc.domain if doc else ''} | "
            f"{doc.processing_mode if doc else ''} | {len(bundle.samples)} | "
            f"{_clip(doc.split_used if doc else '', 90)} | "
            f"`{doc.primary_metric if doc else ''}` |"
        )
    lines.append("")

    if skipped:
        lines.append("## Skipped datasets")
        lines.append("")
        lines.append("| dataset | reason |")
        lines.append("|---|---|")
        for bundle in sorted(skipped, key=lambda b: b.config.id):
            lines.append(f"| `{bundle.config.id}` | {_clip(bundle.skipped_reason or '', 400)} |")
        lines.append("")
        lines.append(
            "Each of these appears in every run's `Skipped` report sheet and in "
            "`RUN_REPORT.md` with the same reason, so a run never silently omits a dataset."
        )
        lines.append("")

    # ---------------- per-dataset detail ---------------- #
    lines.append("## Details")
    lines.append("")
    for bundle in sorted(evaluated, key=lambda b: b.config.id):
        doc = bundle.documentation
        cfg = bundle.config
        lines.append(f"### `{cfg.id}` -- {doc.name if doc else cfg.id}")
        lines.append("")
        lines.append(f"* **Source**: {doc.source_url if doc else ''}")
        lines.append(f"* **Domain / mode**: {doc.domain if doc else ''} / {doc.processing_mode if doc else ''}")
        lines.append(f"* **Adapter**: `{cfg.impl}` (v{bundle.adapter.adapter_version if bundle.adapter else '?'})")
        lines.append(f"* **Items built**: {len(bundle.samples)} (requested {cfg.sample_size})")
        lines.append(f"* **Split used**: {doc.split_used if doc else ''}")
        lines.append(f"* **Abductive subset**: {doc.abductive_subset if doc else ''}")
        lines.append(f"* **Sampling**: {doc.sampling_procedure if doc else ''}")
        if cfg.options:
            lines.append(f"* **Options**: `{cfg.options}`")
        if cfg.prompt_bindings:
            lines.append(f"* **Prompt bindings**: `{cfg.prompt_bindings}`")
        lines.append("")
        if doc and doc.metrics_description:
            lines.append("**Metrics**")
            lines.append("")
            for name, description in doc.metrics_description.items():
                marker = " **(primary)**" if name == doc.primary_metric else ""
                lines.append(f"* `{name}`{marker} -- {description}")
            lines.append("")
        if doc and doc.decisions:
            lines.append("**Decisions**")
            lines.append("")
            for decision in doc.decisions:
                lines.append(f"* {decision}")
            lines.append("")
        if doc and doc.caveats:
            lines.append("**Caveats**")
            lines.append("")
            for caveat in doc.caveats:
                lines.append(f"* {caveat}")
            lines.append("")

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {out_path} ({len(evaluated)} evaluable, {len(skipped)} skipped)")
    return 0


def _clip(text: str, limit: int) -> str:
    text = (text or "").replace("\n", " ").replace("|", "/")
    return text if len(text) <= limit else text[:limit] + "..."


if __name__ == "__main__":
    raise SystemExit(main())
